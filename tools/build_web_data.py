"""Generate web/data.json from the Python package (single source of truth).

Run ``python tools/build_web_data.py`` after changing palettes, presets,
hardware modes or dithers; ``tests/test_web_data.py`` fails when it is stale.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from pixelate import __version__  # noqa: E402
from pixelate.core import _defaults  # noqa: E402
from pixelate.dithering import (  # noqa: E402
    DITHER_DESCRIPTIONS,
    KERNELS,
    PATTERN_CANDIDATES,
    PATTERN_ERROR_MULTIPLIER,
    bayer_matrix,
    blue_noise,
    halftone_matrix,
)
from pixelate.hardware import HARDWARE_MODES  # noqa: E402
from pixelate.palettes import PALETTES  # noqa: E402
from pixelate.presets import PRESETS  # noqa: E402

OUT = ROOT / "web" / "data.json"
OUT_JS = ROOT / "web" / "data.js"


def build() -> dict:
    canonical: dict = {}
    aliases: dict = {}
    for name, colors in PALETTES.items():
        key = tuple(map(tuple, colors))
        if key in canonical:
            aliases[name] = canonical[key]
        else:
            canonical[key] = name
    palettes = {
        name: ["#{:02x}{:02x}{:02x}".format(*c) for c in colors]
        for colors, name in ((list(k), v) for k, v in canonical.items())
    }
    return {
        "version": __version__,
        "palettes": palettes,
        "paletteAliases": aliases,
        "kernels": {k: [list(t) for t in v] for k, v in KERNELS.items()},
        "pattern": {"candidates": PATTERN_CANDIDATES, "multiplier": PATTERN_ERROR_MULTIPLIER},
        "thresholds": {
            name: {"size": int(m.shape[0]), "ranks": [int(v) for v in (m * m.size).round().ravel()]}
            for name, m in (
                ("pattern", bayer_matrix(8)),
                ("halftone", halftone_matrix()),
                ("bluenoise", blue_noise()),
            )
        },
        "defaults": {
            k: (list(v) if isinstance(v, tuple) else v)
            for k, v in _defaults().items()
            if isinstance(v, (int, float, str, bool, tuple, type(None)))
        },
        "dithers": DITHER_DESCRIPTIONS,
        "hardware": {
            m.name: {
                "title": m.title,
                "palette": ["#{:02x}{:02x}{:02x}".format(*c) for c in m.palette],
                "cell": list(m.cell),
                "perCell": m.per_cell,
                "shared": m.shared,
                "maxSets": m.max_sets,
                "groups": [list(g) for g in m.groups],
                "pixelWidth": m.pixel_width,
                "native": list(m.native),
                "notes": m.notes,
            }
            for m in HARDWARE_MODES.values()
        },
        "presets": {
            p.name: {"description": p.description, "options": dict(p.options)}
            for p in PRESETS.values()
        },
    }


def render() -> str:
    return json.dumps(build(), indent=1, sort_keys=False) + "\n"


def render_js() -> str:
    """Same data as a classic script (works from file:// and importScripts)."""
    return (
        "/* Generated by tools/build_web_data.py - do not edit. */\n"
        "(function (root) { root.PIXELATE_DATA = "
        + json.dumps(build(), separators=(",", ":"))
        + "; })(typeof self !== 'undefined' ? self : globalThis);\n"
    )


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    OUT_JS.write_text(render_js(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} and {OUT_JS.relative_to(ROOT)}")
