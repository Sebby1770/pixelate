"""
Export pixel art as data: SVG, JSON, C headers, and palette swatch sheets.

Every exporter works on the *logical* index map (one entry per art pixel,
before upscaling) plus its palette — the result of
:func:`pixelate.core.pixelate_image` carries both on ``result.info``.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Optional, Sequence, Union

import numpy as np
from PIL import Image, ImageDraw, ImageFont

RGB = Sequence[int]
PathLike = Union[str, Path]

EXPORT_SUFFIXES = {".svg": "svg", ".json": "json", ".h": "c", ".c": "c"}


def _hex(c: RGB) -> str:
    return f"#{int(c[0]):02x}{int(c[1]):02x}{int(c[2]):02x}"


def to_svg(
    indices: np.ndarray,
    palette: Sequence[RGB],
    pixel: int = 1,
    transparent: Optional[np.ndarray] = None,
    background: Optional[RGB] = None,
) -> str:
    """
    Vector SVG of an index map. Horizontal runs of one color merge into a
    single ``<rect>`` and rects are grouped per color, so files stay small;
    ``shape-rendering="crispEdges"`` keeps edges sharp at any zoom.
    *transparent* is an optional boolean mask of pixels to leave empty.
    """
    idx = np.asarray(indices)
    h, w = idx.shape
    runs: dict = {}
    for y in range(h):
        row = idx[y]
        mask = None if transparent is None else transparent[y]
        x = 0
        while x < w:
            v = int(row[x])
            start = x
            while x < w and int(row[x]) == v and (mask is None or mask[x] == mask[start]):
                x += 1
            if mask is not None and mask[start]:
                continue
            runs.setdefault(v, []).append((start, y, x - start))
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w * pixel}" height="{h * pixel}" '
        f'viewBox="0 0 {w} {h}" shape-rendering="crispEdges">'
    ]
    if background is not None:
        parts.append(f'<rect width="{w}" height="{h}" fill="{_hex(background)}"/>')
    for v in sorted(runs):
        parts.append(f'<g fill="{_hex(palette[v])}">')
        parts.extend(f'<rect x="{x}" y="{y}" width="{n}" height="1"/>' for x, y, n in runs[v])
        parts.append("</g>")
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def to_json(indices: np.ndarray, palette: Sequence[RGB], **meta) -> str:
    """JSON document: ``{width, height, palette: [#hex], pixels: [[i, ...], ...]}``."""
    idx = np.asarray(indices)
    doc = {
        "format": "pixelate-indexed",
        "version": 1,
        "width": int(idx.shape[1]),
        "height": int(idx.shape[0]),
        "palette": [_hex(c) for c in palette],
        "pixels": idx.astype(int).tolist(),
    }
    doc.update({k: v for k, v in meta.items() if v is not None})
    return json.dumps(doc, separators=(",", ":")) + "\n"


def _c_ident(name: str) -> str:
    ident = re.sub(r"[^0-9a-zA-Z_]", "_", name).strip("_").lower() or "image"
    return "_" + ident if ident[0].isdigit() else ident


def to_c_header(indices: np.ndarray, palette: Sequence[RGB], name: str = "image") -> str:
    """C header with ``<name>_palette`` (RGB triples) and ``<name>_pixels`` (indices)."""
    idx = np.asarray(indices).astype(int)
    h, w = idx.shape
    ident = _c_ident(name)
    guard = ident.upper() + "_H"
    lines = [
        "/* Generated by pixelate — https://github.com/Sebby1770/pixelate */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <stdint.h>",
        "",
        f"#define {ident.upper()}_WIDTH {w}",
        f"#define {ident.upper()}_HEIGHT {h}",
        f"#define {ident.upper()}_COLORS {len(palette)}",
        "",
        f"static const uint8_t {ident}_palette[{len(palette)}][3] = {{",
    ]
    lines += [f"    {{{int(c[0])}, {int(c[1])}, {int(c[2])}}}," for c in palette]
    lines += ["};", "", f"static const uint8_t {ident}_pixels[{h * w}] = {{"]
    for y in range(h):
        lines.append("    " + ", ".join(str(v) for v in idx[y]) + ",")
    lines += ["};", "", f"#endif /* {guard} */", ""]
    return "\n".join(lines)


def export_indexed(
    indices: np.ndarray,
    palette: Sequence[RGB],
    path: PathLike,
    *,
    pixel: int = 1,
    transparent: Optional[np.ndarray] = None,
) -> Path:
    """Write *indices* to *path*, picking SVG / JSON / C by its suffix."""
    p = Path(path)
    kind = EXPORT_SUFFIXES.get(p.suffix.lower())
    if kind is None:
        raise ValueError(f"Unsupported export type '{p.suffix}'. Use .svg, .json, .h or .c")
    p.parent.mkdir(parents=True, exist_ok=True)
    if kind == "svg":
        text = to_svg(indices, palette, pixel=pixel, transparent=transparent)
    elif kind == "json":
        text = to_json(indices, palette, pixel=pixel)
    else:
        text = to_c_header(indices, palette, name=p.stem)
    p.write_text(text, encoding="utf-8")
    return p


def swatch_sheet(
    palette: Sequence[RGB],
    *,
    cols: int = 8,
    swatch: int = 48,
    label: bool = True,
    title: Optional[str] = None,
    bg: RGB = (18, 18, 22),
) -> Image.Image:
    """Render a palette as a grid of labeled swatches (hex codes under each)."""
    if not palette:
        raise ValueError("Palette is empty")
    cols = max(1, min(cols, len(palette)))
    rows = -(-len(palette) // cols)
    pad = 8
    label_h = 14 if label else 0
    title_h = 18 if title else 0
    width = pad + cols * (swatch + pad)
    height = pad + title_h + rows * (swatch + label_h + pad)
    sheet = Image.new("RGB", (width, height), tuple(int(v) for v in bg))
    draw = ImageDraw.Draw(sheet)
    font = ImageFont.load_default()
    if title:
        draw.text((pad, pad), title, fill=(230, 230, 230), font=font)
    for i, c in enumerate(palette):
        r, col = divmod(i, cols)
        x = pad + col * (swatch + pad)
        y = pad + title_h + r * (swatch + label_h + pad)
        draw.rectangle([x, y, x + swatch - 1, y + swatch - 1], fill=tuple(int(v) for v in c[:3]))
        if label:
            draw.text((x, y + swatch + 1), _hex(c)[1:], fill=(200, 200, 200), font=font)
    return sheet
